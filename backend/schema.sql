-- AI Edge Ops reference schema for PostgreSQL.
-- The application currently creates these tables with SQLAlchemy init_db().
-- Keep this file aligned with server/app/modules/*/models.py.

BEGIN;

CREATE TABLE IF NOT EXISTS users (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(128) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_users_email ON users (email);

-- Authorization matrix. Users may have multiple roles; roles may grant
-- multiple permissions through role_permissions.
CREATE TABLE IF NOT EXISTS roles (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64) NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS permissions (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(128) NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id     INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id     INTEGER NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, role_id)
);

CREATE INDEX IF NOT EXISTS ix_user_roles_role_id ON user_roles (role_id);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id       INTEGER NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    permission_id INTEGER NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (role_id, permission_id)
);

CREATE INDEX IF NOT EXISTS ix_role_permissions_permission_id
    ON role_permissions (permission_id);

-- Baseline authorization matrix. Add/remove grants here as the product evolves.
INSERT INTO roles (code, name, description)
VALUES
    ('admin', 'Administrator', 'Full platform access'),
    ('viewer', 'Viewer', 'Read-only platform access')
ON CONFLICT (code) DO NOTHING;

INSERT INTO permissions (code, name, description)
VALUES
    ('users.read', 'Read users', 'View user accounts'),
    ('users.manage', 'Manage users', 'Create and update user accounts'),
    ('observability.read', 'Read observability', 'View violations, alerts, and analytics'),
    ('deployments.manage', 'Manage deployments', 'Activate and manage model deployments')
ON CONFLICT (code) DO NOTHING;

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r CROSS JOIN permissions p
WHERE r.code = 'admin'
ON CONFLICT (role_id, permission_id) DO NOTHING;

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r CROSS JOIN permissions p
WHERE r.code = 'viewer' AND p.code IN ('users.read', 'observability.read')
ON CONFLICT (role_id, permission_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS devices (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(128) NOT NULL UNIQUE,
    site         VARCHAR(128) NOT NULL,
    hardware     VARCHAR(64) NOT NULL,
    ip_address   VARCHAR(64),
    status       VARCHAR(32) NOT NULL DEFAULT 'provisioning',
    labels       JSONB NOT NULL DEFAULT '{}'::jsonb,
    last_seen_at TIMESTAMPTZ,
    agent_version           VARCHAR(32),
    uptime_s                DOUBLE PRECISION,
    active_model_version_id INTEGER,
    backend                 VARCHAR(32),
    arch                    VARCHAR(32),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_devices_name ON devices (name);
CREATE INDEX IF NOT EXISTS ix_devices_site ON devices (site);
CREATE INDEX IF NOT EXISTS ix_devices_status ON devices (status);

CREATE TABLE IF NOT EXISTS metric_samples (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id             INTEGER NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    recorded_at           TIMESTAMPTZ NOT NULL,
    cpu_percent           DOUBLE PRECISION,
    gpu_percent           DOUBLE PRECISION,
    mem_percent           DOUBLE PRECISION,
    temperature_c         DOUBLE PRECISION,
    fps                   DOUBLE PRECISION,
    inference_latency_ms  DOUBLE PRECISION
);

CREATE INDEX IF NOT EXISTS ix_metric_samples_device_id ON metric_samples (device_id);
CREATE INDEX IF NOT EXISTS ix_metric_samples_recorded_at ON metric_samples (recorded_at);

CREATE TABLE IF NOT EXISTS cameras (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(128) NOT NULL UNIQUE,
    source        VARCHAR(512) NOT NULL,
    zone          VARCHAR(128) NOT NULL DEFAULT 'default',
    device_id     INTEGER REFERENCES devices (id) ON DELETE SET NULL,
    enabled       BOOLEAN NOT NULL DEFAULT TRUE,
    metadata_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_cameras_name ON cameras (name);

CREATE TABLE IF NOT EXISTS camera_groups (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(128) NOT NULL UNIQUE,
    description TEXT,
    site        VARCHAR(128) NOT NULL DEFAULT 'default',
    camera_ids  JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_camera_groups_name ON camera_groups (name);

CREATE TABLE IF NOT EXISTS snapshots (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id   INTEGER REFERENCES cameras (id) ON DELETE SET NULL,
    image_path  VARCHAR(512) NOT NULL,
    captured_at VARCHAR(64) NOT NULL,
    labels      JSONB NOT NULL DEFAULT '[]'::jsonb
);

CREATE TABLE IF NOT EXISTS models (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(128) NOT NULL UNIQUE,
    task         VARCHAR(32) NOT NULL,
    architecture VARCHAR(64) NOT NULL,
    description  TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_models_name ON models (name);
CREATE INDEX IF NOT EXISTS ix_models_task ON models (task);

CREATE TABLE IF NOT EXISTS model_versions (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id     INTEGER NOT NULL REFERENCES models (id) ON DELETE CASCADE,
    version      VARCHAR(32) NOT NULL,
    format       VARCHAR(32) NOT NULL,
    compression  VARCHAR(32) NOT NULL DEFAULT 'none',
    status       VARCHAR(32) NOT NULL DEFAULT 'draft',
    artifact_uri VARCHAR(512),
    image_repo        VARCHAR(512),
    image_cpu_digest  VARCHAR(128),
    image_gpu_digest  VARCHAR(128),
    size_mb      DOUBLE PRECISION,
    metrics      JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_model_version UNIQUE (model_id, version)
);

CREATE INDEX IF NOT EXISTS ix_model_versions_model_id ON model_versions (model_id);
CREATE INDEX IF NOT EXISTS ix_model_versions_status ON model_versions (status);

CREATE TABLE IF NOT EXISTS deployments (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id       INTEGER NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    model_version_id INTEGER NOT NULL REFERENCES model_versions (id) ON DELETE RESTRICT,
    status          VARCHAR(32) NOT NULL DEFAULT 'pending',
    config          JSONB NOT NULL DEFAULT '{}'::jsonb,
    note            TEXT,
    activated_at    TIMESTAMPTZ,
    ended_at        TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_deployments_device_id ON deployments (device_id);
CREATE INDEX IF NOT EXISTS ix_deployments_model_version_id ON deployments (model_version_id);
CREATE INDEX IF NOT EXISTS ix_deployments_status ON deployments (status);

CREATE TABLE IF NOT EXISTS violations (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id       INTEGER NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    zone            VARCHAR(128) NOT NULL,
    violation_type  VARCHAR(64) NOT NULL,
    confidence      DOUBLE PRECISION NOT NULL,
    image_path      VARCHAR(512),
    recorded_at     TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_violations_device_id ON violations (device_id);
CREATE INDEX IF NOT EXISTS ix_violations_zone ON violations (zone);
CREATE INDEX IF NOT EXISTS ix_violations_violation_type ON violations (violation_type);
CREATE INDEX IF NOT EXISTS ix_violations_recorded_at ON violations (recorded_at);

CREATE TABLE IF NOT EXISTS alerts (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type          VARCHAR(32) NOT NULL,
    severity      VARCHAR(32) NOT NULL,
    status        VARCHAR(32) NOT NULL DEFAULT 'open',
    title         VARCHAR(256) NOT NULL,
    description   TEXT,
    device_id     INTEGER REFERENCES devices (id) ON DELETE SET NULL,
    deployment_id INTEGER REFERENCES deployments (id) ON DELETE SET NULL,
    context       JSONB NOT NULL DEFAULT '{}'::jsonb,
    resolved_at   TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_alerts_type ON alerts (type);
CREATE INDEX IF NOT EXISTS ix_alerts_severity ON alerts (severity);
CREATE INDEX IF NOT EXISTS ix_alerts_status ON alerts (status);
CREATE INDEX IF NOT EXISTS ix_alerts_device_id ON alerts (device_id);

CREATE TABLE IF NOT EXISTS app_settings (
    key        VARCHAR(128) PRIMARY KEY,
    value      JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action     VARCHAR(128) NOT NULL,
    actor      VARCHAR(128) NOT NULL DEFAULT 'system',
    detail     TEXT,
    created_at VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role       VARCHAR(32) NOT NULL,
    text       TEXT NOT NULL,
    created_at VARCHAR(64) NOT NULL
);

COMMIT;
